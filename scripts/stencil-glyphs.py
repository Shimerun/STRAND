"""Writes src/components/stencilGlyphs.js: the outlines of the footer stencil's letters as polylines.

The variable Montserrat draws a heavy letter from overlapping pieces, so a stroked <text> shows lines inside the
letters. This instantiates the font at the stencil's weight, merges the overlaps, flattens the curves and orients
every contour the way the shears cut it: clockwise on screen, starting at its top-left point, holes first.

Run again when the name (site.name) or TEXT.size in StencilLetter.jsx changes, from a Python 3 environment
outside the project with `pip install fonttools brotli skia-pathops`:
    python scripts/stencil-glyphs.py STRAND
"""

import math
import sys
from pathlib import Path

import pathops
from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "public/fonts/montserrat-latin-wght-normal.woff2"
OUT = ROOT / "src/components/stencilGlyphs.js"
WEIGHT = 800
SIZE = 205  # view units per em, TEXT.size in StencilLetter.jsx
CHORD = 3.0  # view units per flattened curve step


class FlatPen(BasePen):
    """Collects contours as lists of (x, y) in view units: y down, origin on the pen position at the baseline."""

    def __init__(self, scale):
        super().__init__(None)
        self.scale = scale
        self.contours = []

    def _point(self, pt):
        return (pt[0] * self.scale, -pt[1] * self.scale)

    def _moveTo(self, pt):
        self.contours.append([self._point(pt)])

    def _lineTo(self, pt):
        self.contours[-1].append(self._point(pt))

    def _curve(self, points, at):
        start = self.contours[-1][-1]
        pts = [start] + [self._point(p) for p in points]
        hull = sum(math.dist(a, b) for a, b in zip(pts, pts[1:]))
        steps = max(1, math.ceil(hull / CHORD))
        for i in range(1, steps + 1):
            self.contours[-1].append(at(pts, i / steps))

    def _qCurveToOne(self, p1, p2):
        def at(pts, t):
            (x0, y0), (x1, y1), (x2, y2) = pts
            u = 1 - t
            return (u * u * x0 + 2 * u * t * x1 + t * t * x2, u * u * y0 + 2 * u * t * y1 + t * t * y2)

        self._curve([p1, p2], at)

    def _curveToOne(self, p1, p2, p3):
        def at(pts, t):
            (x0, y0), (x1, y1), (x2, y2), (x3, y3) = pts
            u = 1 - t
            a, b, c, d = u**3, 3 * u * u * t, 3 * u * t * t, t**3
            return (a * x0 + b * x1 + c * x2 + d * x3, a * y0 + b * y1 + c * y2 + d * y3)

        self._curve([p1, p2, p3], at)

    def _closePath(self):
        contour = self.contours[-1]
        if len(contour) > 1 and math.dist(contour[0], contour[-1]) < 1e-6:
            contour.pop()


def signed_area(points):
    """Positive when the contour runs clockwise on screen (y down)."""
    return sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(points, points[1:] + points[:1])) / 2


def letter_contours(font, glyph_set, char):
    name = font.getBestCmap().get(ord(char))
    if name is None:
        raise SystemExit(f"The font has no glyph for {char!r}")
    path = pathops.Path()
    glyph_set[name].draw(path.getPen())
    path.simplify(fix_winding=True)
    pen = FlatPen(SIZE / font["head"].unitsPerEm)
    path.draw(pen)
    contours = [c for c in pen.contours if len(c) > 2]
    outer_sign = math.copysign(1, signed_area(max(contours, key=lambda c: abs(signed_area(c)))))
    oriented = []
    for points in contours:
        hole = math.copysign(1, signed_area(points)) != outer_sign
        if signed_area(points) < 0:
            points = points[::-1]
        top = min(range(len(points)), key=lambda i: (round(points[i][1] * 2), points[i][0]))
        oriented.append((not hole, points[top][0], points[top:] + points[:top]))
    oriented.sort(key=lambda item: (item[0], item[1]))  # holes first, each group left to right
    return [points for _, _, points in oriented]


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: stencil-glyphs.py WORD")
    word = sys.argv[1].upper()
    font = instancer.instantiateVariableFont(TTFont(FONT), {"wght": WEIGHT})
    glyph_set = font.getGlyphSet()
    lines = [
        "// Generated by scripts/stencil-glyphs.py; run it again rather than editing this file.",
        f"// Montserrat {WEIGHT} at {SIZE} view units, overlaps merged: per letter its contours as flat [x, y, ...] lists",
        "// from the pen position on the baseline (y down), clockwise on screen from the top-left point, holes first.",
        f"export const GLYPH_SIZE = {SIZE};",
        "export const GLYPHS = {",
    ]
    for char in dict.fromkeys(word):
        flat = [", ".join(f"{v:.1f}".rstrip("0").rstrip(".") for p in c for v in p) for c in letter_contours(font, glyph_set, char)]
        lines.append(f"  {char}: [" + ", ".join(f"[{c}]" for c in flat) + "],")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
